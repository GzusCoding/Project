<?php

declare(strict_types=1);

$supportedLanguages = ["th", "en"];
$requestedLanguage = $_GET["lang"] ?? null;
if (
    session_status() === PHP_SESSION_ACTIVE
    && is_string($requestedLanguage)
    && in_array($requestedLanguage, $supportedLanguages, true)
) {
    $_SESSION["language"] = $requestedLanguage;
    $secureCookie = !empty($_SERVER["HTTPS"]) && strtolower((string) $_SERVER["HTTPS"]) !== "off";
    setcookie("marketplace_language", $requestedLanguage, [
        "expires" => time() + 365 * 24 * 60 * 60,
        "path" => "/",
        "secure" => $secureCookie,
        "httponly" => true,
        "samesite" => "Lax"
    ]);
} elseif (
    session_status() === PHP_SESSION_ACTIVE
    && !in_array($_SESSION["language"] ?? null, $supportedLanguages, true)
) {
    $cookieLanguage = $_COOKIE["marketplace_language"] ?? null;
    $_SESSION["language"] = is_string($cookieLanguage)
        && in_array($cookieLanguage, $supportedLanguages, true)
            ? $cookieLanguage
            : "th";
}

function app_language(): string
{
    $language = $_SESSION["language"] ?? $_COOKIE["marketplace_language"] ?? "th";

    return in_array($language, ["th", "en"], true) ? $language : "th";
}

