function language_switcher(): string
{
    $path = parse_url($_SERVER["REQUEST_URI"] ?? "/", PHP_URL_PATH);
    if (!is_string($path) || $path === "") {
        $path = "/";
    }
    $query = is_array($_GET) ? $_GET : [];
    unset($query["lang"]);
    $links = [];
    foreach (["th" => "ไทย", "en" => "English"] as $language => $label) {
        $languageQuery = $query;
        $languageQuery["lang"] = $language;
        $href = $path . "?" . http_build_query($languageQuery);
        $current = app_language() === $language ? ' aria-current="true"' : "";
        $links[] = '<a href="' . htmlspecialchars($href, ENT_QUOTES, "UTF-8") . '"' . $current . ">"
            . $label . "</a>";
    }

    return '<nav class="language-switcher" aria-label="' . htmlspecialchars(t("Language"), ENT_QUOTES, "UTF-8")
        . '">' . implode('<span aria-hidden="true"> · </span>', $links) . "</nav>";
}
